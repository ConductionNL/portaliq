interface TrafficPathsInterface {

	/**
	 * The most steps after the start or end point.
	 */
	public const MAX_STEPS = 10;

	/**
	 * Read forward from the start point, or backward from the end point.
	 *
	 * @var string[]
	 */
	public const MODES = ['start', 'end'];
}//end interface
