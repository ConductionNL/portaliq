/**
 * The placements a component may have, in the order design D1 lists them.
 *
 * @type {Array<string>}
 */
export const NLDS_PLACEMENTS = ['widget', 'field', 'part', 'inline', 'shell', 'none']

/**
 * How many of each placement the record holds.
 *
 * @return {Record<string, number>} The count per placement.
 */
export function coverageByPlacement() {
	const counts = {}
	for (const placement of NLDS_PLACEMENTS) {
		counts[placement] = 0
	}

	for (const entry of NLDS_COVERAGE) {
		counts[entry.placement] = (counts[entry.placement] ?? 0) + 1
	}

	return counts
}

